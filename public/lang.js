// Varsayılan dil (localStorage > cookie > AZ)
function getCookieLang() {
    const match = document.cookie.match(/(?:^|; )lang_default=([^;]+)/);
    return match ? decodeURIComponent(match[1]) : '';
}

const storedLang = localStorage.getItem("lang");
const cookieLang = getCookieLang();
const isValidLang = (v) => v === "az" || v === "tr" || v === "en";
let currentLang = isValidLang(storedLang) ? storedLang : (isValidLang(cookieLang) ? cookieLang : "az");

function applyLanguage() {
    const elements = document.querySelectorAll("[data-i18n]");
    elements.forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (translations[currentLang] && translations[currentLang][key]) {
            if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
                el.placeholder = translations[currentLang][key];
            } else {
                el.textContent = translations[currentLang][key];
            }
        }
    });


    const banner = document.getElementById("siteAnnouncement");
    const bannerText = document.getElementById("siteAnnouncementText");
    if (banner && bannerText) {
        const az = banner.getAttribute("data-az") || "";
        const tr = banner.getAttribute("data-tr") || "";
        const en = banner.getAttribute("data-en") || "";
        const textValue = currentLang === "tr" ? (tr || az || en) : (currentLang === "en" ? (en || az || tr) : (az || tr || en));
        bannerText.textContent = textValue;
        if (!textValue) {
            banner.classList.add("d-none");
        } else {
            banner.classList.remove("d-none");
        }
    }

    if (typeof window.applyNotificationLanguage === 'function') {
        window.applyNotificationLanguage();
    }
    if (typeof window.refreshCustomDomainUi === 'function') {
        window.refreshCustomDomainUi();
    }
    const toggleBtn = document.getElementById("langToggleBtn");
    if (toggleBtn) {
        toggleBtn.textContent = currentLang.toUpperCase();
    }

    const langOptions = document.querySelectorAll(".lang-option");
    if (langOptions.length) {
        langOptions.forEach(option => {
            const optionLang = option.getAttribute("data-lang");
            const labelKey = optionLang === "az" ? "lang_az" : (optionLang === "tr" ? "lang_tr" : "lang_en");
            if (translations[currentLang] && translations[currentLang][labelKey]) {
                option.textContent = translations[currentLang][labelKey];
            } else if (optionLang) {
                option.textContent = optionLang.toUpperCase();
            }
            const isActive = optionLang === currentLang;
            option.classList.toggle("active", isActive);
            if (isActive) {
                option.setAttribute("aria-current", "true");
            } else {
                option.removeAttribute("aria-current");
            }
        });
    }

    // HTML lang attribute güncelle
    document.documentElement.lang = currentLang;
}

function setLanguage(lang) {
    if (!isValidLang(lang)) return;
    currentLang = lang;
    localStorage.setItem("lang", currentLang);
    applyLanguage();
    window.dispatchEvent(new CustomEvent("ovlink:languageChanged", { detail: { lang: currentLang } }));
}

function toggleLanguage() {
    const nextLang = currentLang === "az" ? "tr" : (currentLang === "tr" ? "en" : "az");
    setLanguage(nextLang);
}

window.addEventListener("DOMContentLoaded", () => {
    applyLanguage();

    const langOptions = document.querySelectorAll(".lang-option");
    if (langOptions.length) {
        langOptions.forEach(option => {
            option.addEventListener("click", (e) => {
                e.preventDefault();
                const selected = option.getAttribute("data-lang");
                setLanguage(selected);
            });
        });
        return;
    }

    const toggleBtn = document.getElementById("langToggleBtn");
    if (toggleBtn) {
        toggleBtn.addEventListener("click", (e) => {
            e.preventDefault();
            toggleLanguage();
        });
    }
});


